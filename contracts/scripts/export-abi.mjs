import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = resolve(here, "../artifacts/contracts/WalkMe.sol/WalkMe.json");
const outPath = resolve(here, "../../web/lib/walkMeAbi.ts");

const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// Generated by contracts/scripts/export-abi.mjs — do not edit by hand.\nexport const walkMeAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`ABI written to ${outPath} (${artifact.abi.length} entries)`);
